// Builds levels/pack-0001.js ... from out/501.json upward (500 levels per pack) and levels/packs.js.
// Usage: node merge-packs.js ../../levels
const fs=require('fs');const dir=process.argv[2]||'../../levels',BUILT=500,PS=500;fs.mkdirSync(dir,{recursive:true});
let n=BUILT+1;const levels=[];
while(fs.existsSync('out/'+n+'.json')){const j=JSON.parse(fs.readFileSync('out/'+n+'.json'));levels.push(j.b?{s:j.s,p:j.p,b:j.b}:{s:j.s,p:j.p});n++}
const seen=new Set();let dup=0;levels.forEach(l=>{const k=JSON.stringify(l);if(seen.has(k))dup++;seen.add(k)});
const packs=Math.ceil(levels.length/PS);
for(let k=1;k<=packs;k++)fs.writeFileSync(dir+'/pack-'+String(k).padStart(4,'0')+'.js','(window.LV_PACKS=window.LV_PACKS||{})['+k+']='+JSON.stringify(levels.slice((k-1)*PS,k*PS))+';\n');
fs.writeFileSync(dir+'/packs.js','// Generated by merge-packs.js. LV_EXTRA = levels available after the built-in 500.\nwindow.LV_EXTRA='+levels.length+';window.LV_PACKS=window.LV_PACKS||{};\n');
console.log('extra levels',levels.length,'packs',packs,'duplicates',dup);
